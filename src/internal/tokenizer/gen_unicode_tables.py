#!/usr/bin/env python3
"""Regenerate unicode_tables.h from the Unicode data of the `tokenizers` package.

The HunyuanOCR pre-tokenizer uses \\p{N}, \\p{L}, \\p{M}, \\p{P}, \\p{S} and \\s. Hugging Face
`tokenizers` evaluates these with Oniguruma, whose Unicode version can be newer than Python's
`unicodedata`, so membership is probed from the library itself instead of computed locally.

Usage: gen_unicode_tables.py [output_header]
"""

from __future__ import annotations

import sys
from pathlib import Path

from tokenizers import Regex, pre_tokenizers

CLASSES = (("N", r"\p{N}"), ("L", r"\p{L}"), ("M", r"\p{M}"), ("P", r"\p{P}"), ("S", r"\p{S}"))
WHITESPACE = ("WS", r"\s")


def members(pattern: str, codepoints: list[int], text: str) -> set[int]:
    splitter = pre_tokenizers.Split(Regex(pattern), "removed")
    kept: set[int] = set()
    for piece, _ in splitter.pre_tokenize_str(text):
        kept.update(map(ord, piece))
    return set(codepoints) - kept


def build_ranges() -> list[tuple[int, int, str]]:
    codepoints = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]
    text = "".join(map(chr, codepoints))
    owner: dict[int, str] = {}
    for name, pattern in (*CLASSES, WHITESPACE):
        for cp in members(pattern, codepoints, text):
            if cp in owner:
                raise SystemExit(f"U+{cp:04X} is in both {owner[cp]} and {name}")
            owner[cp] = name
    ranges: list[tuple[int, int, str]] = []
    for cp in sorted(owner):
        name = owner[cp]
        if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == name:
            ranges[-1] = (ranges[-1][0], cp, name)
        else:
            ranges.append((cp, cp, name))
    return ranges


def render(ranges: list[tuple[int, int, str]]) -> str:
    import tokenizers

    lines = [
        "// Generated by gen_unicode_tables.py from tokenizers "
        f"{tokenizers.__version__}; do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace hunyuan_ocr::internal {",
        "",
        "enum class UnicodeClass : uint8_t { kOther = 0, kN, kL, kM, kP, kS, kSpace };",
        "",
        "struct UnicodeRange {",
        "    uint32_t first;",
        "    uint32_t last;",
        "    UnicodeClass cls;",
        "};",
        "",
        "// Sorted, non-overlapping. Code points not listed are UnicodeClass::kOther.",
        "// clang-format off",
        "inline constexpr UnicodeRange kUnicodeRanges[] = {",
    ]
    tag = {"N": "kN", "L": "kL", "M": "kM", "P": "kP", "S": "kS", "WS": "kSpace"}
    for first, last, name in ranges:
        lines.append(f"    {{0x{first:X}, 0x{last:X}, UnicodeClass::{tag[name]}}},")
    lines += ["};", "// clang-format on", "", "}  // namespace hunyuan_ocr::internal", ""]
    return "\n".join(lines)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("unicode_tables.h")
    ranges = build_ranges()
    out.write_text(render(ranges), encoding="utf-8")
    print(f"wrote {len(ranges)} ranges to {out}")


if __name__ == "__main__":
    main()
