#!/usr/bin/env python3
"""Capture reviewed goldens for a backend-specific AR profile.

The official Hugging Face FP32 CPU output is generated by
``generate_e2e_reference``.  Vulkan profiles are intentionally independent:
their goldens are captured on the fixed reference GPU and are not silently
compared with the CPU sequence.  DFlash reuses the AR golden for its backend.
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from tools.validation.e2e_contract import build_golden, sha256_file
from tools.validation.runtime_command import runtime_command

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MANIFEST = ROOT / "tests" / "data" / "e2e_strict_samples.json"
PROFILES = ("vulkan_fp32_ar", "vulkan_mixed_ar")


def load_samples(path: Path, limit: int | None) -> list[dict[str, Any]]:
    samples = json.loads(path.read_text(encoding="utf-8"))
    if limit is not None:
        if limit <= 0:
            raise SystemExit("--limit must be positive")
        samples = samples[:limit]
    return samples


def profile_golden(sample: dict[str, Any], profile: str) -> str:
    try:
        return sample["profile_goldens"][profile]
    except KeyError as exc:
        raise SystemExit(f"sample {sample['id']} has no profile golden for {profile}") from exc


def host_fingerprint(vulkan_device: int) -> dict[str, str]:
    fingerprint = {
        "platform": platform.platform(),
        "machine": platform.machine(),
        "python": platform.python_version(),
    }
    try:
        result = subprocess.run(
            [
                "nvidia-smi",
                f"--id={vulkan_device}",
                "--query-gpu=name,driver_version,compute_cap",
                "--format=csv,noheader,nounits",
            ],
            capture_output=True,
            text=True,
            check=False,
            timeout=10,
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        result = None
    if result is not None and result.returncode == 0:
        fingerprint["nvidia_smi"] = " ".join(result.stdout.strip().split())
    return fingerprint


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", required=True, choices=PROFILES)
    parser.add_argument("--model", type=Path, default=ROOT / "assets" / "hunyuan_ocr")
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--out-root", type=Path, required=True)
    parser.add_argument("--build-dir", type=Path, default=ROOT / "build-vulkan")
    parser.add_argument("--threads", type=int, default=4)
    parser.add_argument("--vulkan-device", type=int, default=0)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    if args.threads <= 0:
        raise SystemExit("--threads must be positive")
    if args.vulkan_device < 0:
        raise SystemExit("--vulkan-device must be non-negative")

    executable = args.build_dir / "hunyuan-ocr"
    if not executable.is_file():
        raise SystemExit(f"missing Vulkan executable: {executable}")
    samples = load_samples(args.manifest, args.limit)
    provenance_base = {
        "profile": args.profile,
        "executable_sha256": sha256_file(executable),
        "runtime_model_json_sha256": sha256_file(args.model / "model.json"),
        "vulkan_device": args.vulkan_device,
        "host": host_fingerprint(args.vulkan_device),
    }

    with tempfile.TemporaryDirectory(prefix="hunyuan-ocr-goldens-") as temp_dir:
        temp_root = Path(temp_dir)
        for sample in samples:
            image = ROOT / sample["image"]
            output_path = args.out_root / profile_golden(sample, args.profile)
            if output_path.exists() and not args.overwrite:
                raise SystemExit(f"golden exists; pass --overwrite explicitly: {output_path}")
            report_path = temp_root / f"{sample['id']}.json"
            subprocess.run(
                runtime_command(
                    executable,
                    args.model,
                    image,
                    sample,
                    args.profile,
                    args.threads,
                    args.vulkan_device,
                    report_path,
                ),
                cwd=ROOT,
                check=True,
                timeout=3600,
            )
            report = json.loads(report_path.read_text(encoding="utf-8"))
            provenance = dict(provenance_base)
            provenance["command"] = runtime_command(
                executable,
                args.model,
                image,
                sample,
                args.profile,
                args.threads,
                args.vulkan_device,
                Path("<json-output>"),
            )
            golden = build_golden(sample, report, image, provenance)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(json.dumps(golden, ensure_ascii=False, indent=2) + "\n")
            print(
                f"[runtime_golden] {args.profile} {sample['id']} "
                f"tokens={len(report['generated_token_ids'])} -> {output_path}"
            )


if __name__ == "__main__":
    main()
